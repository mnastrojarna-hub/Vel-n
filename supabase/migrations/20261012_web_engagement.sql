-- FEAT (zadání majitele 2026-10-12): Velín → Analýza → Web funnel —
--   • počet NÁVŠTĚV vs. počet ZAHÁJENÝCH rezervací,
--   • kolik lidí POUŽILO KALKULAČKU ceny.
-- Návštěva = člověk zůstal na JAKÉKOLI stránce aspoň 5 s (viditelná karta) —
-- striktně jen lidé, žádní boti. Připraveno i pro appku (`source = 'app'`).
--
-- Zápis: web PHP `/api/engage` (motogo-web-php/engage.php) po beaconu z
-- `js/engage.js` — JS běží jen v prohlížeči, beacon odejde až po 5 s
-- viditelné karty + lidské interakci, ne pod webdriverem; server navíc pustí
-- jen UA reálného prohlížeče, známou doménu a same-origin požadavek.
-- Cookieless: `visitor_hash` = sha256(IP|UA|UTC den|salt) jako `visitor_log`.
--
-- 1 řádek = 1 člověk × den × událost (unikátní index) → „návštěvy“ = lidé
-- za den (stejně jako unikátní návštěvníci v Analýza → Návštěvnost).
-- Insert jako u `visitor_log` (anon INSERT, RLS check hodnot), čtení jen
-- admin přes RPC `get_web_engagement_daily` (bez EXECUTE pro anon).
-- Idempotentní.
-- =============================================================================

CREATE TABLE IF NOT EXISTS public.web_engagement (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at   timestamptz NOT NULL DEFAULT now(),
  day          date NOT NULL DEFAULT (now() AT TIME ZONE 'Europe/Prague')::date,
  source       text NOT NULL DEFAULT 'web',
  event        text NOT NULL,
  visitor_hash text NOT NULL,
  host         text,
  path         text,
  device       text,
  lang         text,
  CONSTRAINT web_engagement_source_check CHECK (source IN ('web', 'app')),
  CONSTRAINT web_engagement_event_check  CHECK (event IN ('visit', 'calc')),
  CONSTRAINT web_engagement_hash_check   CHECK (visitor_hash ~ '^[0-9a-f]{64}$'),
  CONSTRAINT web_engagement_len_check    CHECK (
    coalesce(length(host), 0) <= 100 AND coalesce(length(path), 0) <= 300
    AND coalesce(length(device), 0) <= 20 AND coalesce(length(lang), 0) <= 10)
);

COMMENT ON TABLE public.web_engagement IS
  'Kvalifikované návštěvy (≥5 s na stránce, jen lidé) a použití kalkulačky — 1 řádek = člověk × den × událost. Zapisuje web /api/engage (anon), čte Velín přes get_web_engagement_daily.';

CREATE UNIQUE INDEX IF NOT EXISTS uq_web_engagement_day_person
  ON public.web_engagement (day, source, event, visitor_hash);

ALTER TABLE public.web_engagement ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS web_engagement_insert ON public.web_engagement;
CREATE POLICY web_engagement_insert ON public.web_engagement
  FOR INSERT TO anon, authenticated
  WITH CHECK (
    day = (now() AT TIME ZONE 'Europe/Prague')::date
    AND created_at > now() - interval '5 minutes'
    AND created_at < now() + interval '5 minutes'
  );

DROP POLICY IF EXISTS web_engagement_admin_select ON public.web_engagement;
CREATE POLICY web_engagement_admin_select ON public.web_engagement
  FOR SELECT TO authenticated
  USING (public.is_admin());

REVOKE ALL ON public.web_engagement FROM anon, authenticated;
GRANT INSERT (source, event, visitor_hash, host, path, device, lang)
  ON public.web_engagement TO anon, authenticated;
GRANT SELECT ON public.web_engagement TO authenticated;
GRANT ALL ON public.web_engagement TO service_role;

-- Denní agregace pro Velín (lidé za den: návštěvy ≥5 s / použili kalkulačku).
CREATE OR REPLACE FUNCTION public.get_web_engagement_daily(
  p_from   date DEFAULT NULL,
  p_to     date DEFAULT NULL,
  p_source text DEFAULT 'web'
) RETURNS jsonb
  LANGUAGE plpgsql
  STABLE
  SECURITY DEFINER
  SET search_path TO 'public'
AS $$
BEGIN
  IF NOT coalesce(public.is_admin(), false) THEN
    RAISE EXCEPTION 'forbidden' USING ERRCODE = '42501';
  END IF;
  RETURN coalesce((
    SELECT jsonb_agg(jsonb_build_object('day', x.day, 'visits', x.visits, 'calc', x.calc) ORDER BY x.day)
    FROM (
      SELECT e.day,
             count(*) FILTER (WHERE e.event = 'visit') AS visits,
             count(*) FILTER (WHERE e.event = 'calc')  AS calc
      FROM public.web_engagement e
      WHERE e.source = coalesce(p_source, 'web')
        AND (p_from IS NULL OR e.day >= p_from)
        AND (p_to   IS NULL OR e.day <= p_to)
      GROUP BY e.day
    ) x
  ), '[]'::jsonb);
END;
$$;

REVOKE ALL ON FUNCTION public.get_web_engagement_daily(date, date, text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.get_web_engagement_daily(date, date, text) TO authenticated, service_role;
