/// Faktury in the v2 look (PLAN §2.5.2, seam view of `InvoicesScreen`):
/// dark compact app bar, year groups (dark eyebrow), white rows with type
/// icons and right-aligned tabular amounts (credit note "−" red). Rows are
/// the existing `InvoiceTile` (its v2 look; same viewer). Empty / loading /
/// error = today's texts and state widgets.
class InvoicesViewV2 extends StatelessWidget {
  final AsyncValue<List<UserInvoice>> invoicesAsync;
  final (Map<int, List<UserInvoice>>, List<int>) Function(List<UserInvoice>) groupByYear;
  final VoidCallback onBack;
  final VoidCallback onBackOr;
  final VoidCallback onRetry;

  const InvoicesViewV2({
    super.key,
    required this.invoicesAsync,
    required this.groupByYear,
    required this.onBack,
    required this.onBackOr,
    required this.onRetry,
  });

  @override
  Widget build(BuildContext context) {
    final tr = t(context);
    final slivers = invoicesAsync.when<List<Widget>>(
      data: (invoices) {
        if (invoices.isEmpty) {
          return [
            SliverFillRemaining(
              hasScrollBody: false,
              child: Center(
                child: Padding(
                  padding: const EdgeInsets.all(24),
                  child: Column(mainAxisSize: MainAxisSize.min, children: [
                    Container(
                      width: 72,
                      height: 72,
                      decoration: BoxDecoration(color: MgColors.well, shape: BoxShape.circle, border: Border.all(color: MgColors.line)),
                      child: const Center(child: MgIcon(MgIcons.receipt, size: 34, color: MgColors.link)),
                    ),
                    const SizedBox(height: 16),
                    Text(tr.tr('noInvoices'), textAlign: TextAlign.center, style: MgType.h3.copyWith(color: MgColors.ink)),
                    const SizedBox(height: 6),
                    Text(tr.tr('invoicesAutoGenerated'),
                        textAlign: TextAlign.center, style: MgType.body.copyWith(color: MgColors.lead)),
                  ]),
                ),
              ),
            ),
          ];
        }
        final (grouped, years) = groupByYear(invoices);
        return [
          SliverToBoxAdapter(
            child: Column(crossAxisAlignment: CrossAxisAlignment.stretch, children: [
              for (var y = 0; y < years.length; y++) ...[
                PfSectionLabel('${years[y]}',
                    padding: EdgeInsets.fromLTRB(16, y == 0 ? 20 : 28, 16, 12)),
                for (var i = 0; i < grouped[years[y]]!.length; i++)
                  Padding(
                    padding: const EdgeInsets.fromLTRB(16, 0, 16, 8),
                    child: MgReveal(index: i, child: InvoiceTile(invoice: grouped[years[y]]![i])),
                  ),
              ],
            ]),
          ),
        ];
      },
      loading: () => [SliverFillRemaining(child: MgLoadingView(onRetry: onRetry, onBack: onBackOr))],
      error: (e, _) => [
        SliverFillRemaining(
          child: MgErrorView(error: e, what: tr.tr('eoInvoicesLoadFail'), onRetry: onRetry, onBack: onBackOr),
        ),
      ],
    );
    return MgPage(
      header: MgAppBar(title: tr.tr('invoicesTitle'), onBack: onBack),
      overlapHero: false,
      slivers: slivers,
    );
  }
}

/// v2 look of one invoice row (white card, type icon tile, number / type,
/// date, amount right — credit note red with "−").
class InvoiceRowV2 extends StatelessWidget {
  final String type;
  final String title;
  final String date;
  final String? amount;
  final bool creditNote;
  final VoidCallback onTap;
  const InvoiceRowV2({
    super.key,
    required this.type,
    required this.title,
    required this.date,
    required this.amount,
    required this.creditNote,
    required this.onTap,
  });

  static String iconFor(String type) => switch (type) {
        'proforma' || 'advance' => MgIcons.receipt,
        'final' => MgIcons.bill,
        'payment_receipt' => MgIcons.checkCircle,
        'shop_final' => MgIcons.cart,
        'credit_note' => MgIcons.swap,
        _ => MgIcons.doc,
      };

  @override
  Widget build(BuildContext context) {
    final fg = creditNote ? MgColors.err : MgColors.ink;
    return MgFabAvoid(
      kind: MgAvoidKind.tap,
      child: Semantics(
        button: true,
        child: MgPress(
          scale: 0.985,
          onTap: onTap,
          child: Container(
            constraints: const BoxConstraints(minHeight: 64),
            padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 12),
            decoration: BoxDecoration(
              color: MgColors.surface,
              borderRadius: BorderRadius.circular(16),
              border: Border.all(color: creditNote ? MgColors.errBorder : MgColors.line),
              boxShadow: MgShadows.card,
            ),
            child: Row(children: [
              Container(
                width: 40,
                height: 40,
                decoration: BoxDecoration(
                  color: creditNote ? MgColors.errBg : MgColors.well,
                  borderRadius: BorderRadius.circular(12),
                  border: Border.all(color: creditNote ? MgColors.errBorder : MgColors.line),
                ),
                child: Center(child: MgIcon(iconFor(type), size: 22, color: creditNote ? MgColors.err : MgColors.link)),
              ),
              const SizedBox(width: 12),
              Expanded(
                child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                  Text(title, style: MgType.title.copyWith(fontWeight: FontWeight.w700, color: fg)),
                  Text(date, style: MgType.tab(MgType.meta.copyWith(color: MgColors.meta))),
                ]),
              ),
              if (amount != null) ...[
                const SizedBox(width: 8),
                Text(amount!, style: MgType.tab(MgType.title.copyWith(fontWeight: FontWeight.w900, color: fg))),
              ],
              const SizedBox(width: 4),
              const MgIcon(MgIcons.chevronRight, size: 18, color: MgColors.meta),
            ]),
          ),
        ),
      ),
    );
  }
}
